"""
MASAISAI live dashboard (Streamlit).

Reworked 27 Jul 2026 (later the same night) from a per-node "utilization console" into a
fused, per-channel "idle-verification" console -- see `Pitching and Presenting/
04_ANTICIPATED_QUESTIONS.md` section 1. The AI's job is no longer forecasting a future window
to feed a grant/deny decision: it fuses several independently noisy, confidence-scored sensing
nodes into one robust, current-window verdict on whether a band is genuinely idle, which a
single sensor or an unweighted majority vote can't do as reliably (see occupancy_model.py's
module docstring for the full "why AI" argument, and the fusion-vs-naive-vote numbers surfaced
below). This dashboard exists to show, plainly, both how the AI reaches that verdict and the
raw sensor data it's built from.

Chosen over Grafana/InfluxDB for zero extra infrastructure to stand up for a bootcamp demo --
same reasoning as the Part 5 fault-injection testbed's dashboard. Runs entirely against the
synthetic sensing data generated by sensing_sim.py plus the trained fusion model and
constraint engine, so it works without any real SDR hardware connected.

Run: streamlit run dashboard_app.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pandas as pd
import streamlit as st

from constraint_engine import decide_access, load_rules
from occupancy_model import (
    ENERGY_DETECTION_THRESHOLD_DBM,
    FEATURE_COLUMNS,
    build_fusion_frame,
    predict_model_proba,
    run_comparison,
    train_model,
)
from sensing_sim import generate_dataset

st.set_page_config(page_title="MASAISAI -- AI Idle-Verification Console", layout="wide")

st.title("MASAISAI -- AI-Verified Spectrum Idle Console")
st.caption(
    "One band, UHF TV white space (470-694 MHz). Simulated demo: synthetic sensing data (no "
    "real SDR hardware connected in this environment). The AI fuses several nodes' noisy "
    "readings into one verified idle/occupied verdict per channel -- it never grants access "
    "or makes a final call; every flag is a triage signal for POTRAZ's own review."
)


@st.cache_data
def load_data():
    raw = generate_dataset(n_days=14, test_period_days=4, seed=3)
    fused = build_fusion_frame(raw)
    return raw, fused


@st.cache_resource
def get_model(train_df: pd.DataFrame):
    return train_model(train_df)


raw, fused = load_data()
train_df = fused[fused["split"] == "train"]
test_df = fused[fused["split"] == "test"].copy()
model = get_model(train_df)
rules = load_rules()

test_df["ml_probability"] = predict_model_proba(model, test_df)
band_utilization_pct = test_df["occupied"].mean() * 100

comparison = run_comparison(train_df, test_df)

col1, col2, col3, col4 = st.columns(4)
col1.metric("Sensing nodes", raw["node_id"].nunique())
col2.metric("Channels monitored (this band)", test_df["channel"].nunique())
col3.metric("Band-wide utilization (test period)", f"{band_utilization_pct:.1f}%")
col4.metric("Protected channels (rules layer)", len(rules.get("protected_channels", [])))

st.subheader("How the AI verifies idle")
ai_col1, ai_col2 = st.columns([3, 2])
with ai_col1:
    st.markdown(
        "A single node's own energy-detection threshold "
        f"(RSSI > {ENERGY_DETECTION_THRESHOLD_DBM:.0f} dBm, the same cutoff the sensing "
        "firmware uses) can be wrong on its own -- multipath fade, transient interference, or "
        "just standing somewhere with poor signal geometry. An unweighted majority vote "
        "across nodes helps, but treats every node's vote equally regardless of how "
        "trustworthy that particular reading is. The model instead fuses each channel's "
        "mean/min/max/spread RSSI, confidence-weighted vote, and recent history into one "
        "learned, auditable verdict."
    )
with ai_col2:
    st.metric("Naive-vote baseline accuracy", f"{comparison['baseline_score']['accuracy']*100:.1f}%")
    st.metric("AI fusion model accuracy", f"{comparison['ml_score']['accuracy']*100:.1f}%")
    st.caption(
        f"Baseline recall {comparison['baseline_score']['recall']*100:.1f}% -- its errors are "
        "missed occupancy (the dangerous direction for incumbent protection), not false alarms."
    )

st.subheader("Band utilization over time (hour of day)")
st.caption(
    "How much of this band is actually occupied, by hour -- the visibility POTRAZ doesn't "
    "currently have from a static ZNFAP allocation table alone."
)
hourly_utilization = test_df.groupby("hour")["occupied"].mean() * 100
st.line_chart(hourly_utilization, x_label="Hour of day", y_label="Utilization %")

st.subheader("Verified idle status by channel (latest fused reading)")
latest = (
    test_df.sort_values(["day_index", "hour"])
    .groupby("channel")
    .tail(1)
    .reset_index(drop=True)
)

decisions = [
    # Fail-safe gate uses the BEST contributing node's confidence, not the mean across all of
    # them -- fusion's whole point is that one reliable node is enough to trust a reading even
    # when several others are degraded; a mean would punish a channel for having any poor
    # nodes at all, discarding exactly the redundancy fusion is supposed to exploit.
    decide_access("FUSED", row.channel, row.ml_probability, row.max_confidence, rules)
    for row in latest.itertuples()
]
latest["classification"] = ["VERIFIED IDLE" if d.granted else "FLAGGED FOR REVIEW" for d in decisions]
latest["reason"] = [d.reason for d in decisions]

display_cols = [
    "channel", "day_index", "hour", "mean_rssi_dbm", "naive_vote_frac",
    "max_confidence", "ml_probability", "classification", "reason",
]
st.dataframe(latest[display_cols].sort_values("channel"), use_container_width=True)

verified_count = (latest["classification"] == "VERIFIED IDLE").sum()
flagged_count = (latest["classification"] == "FLAGGED FOR REVIEW").sum()
st.subheader(f"This snapshot: {verified_count} verified idle / {flagged_count} flagged for review")

st.subheader("The dataset: raw per-node readings behind one channel's verdict")
pick_channel = st.selectbox("Channel", sorted(latest["channel"].unique()))
picked = latest[latest["channel"] == pick_channel].iloc[0]
raw_for_snapshot = raw[
    (raw["day_index"] == picked["day_index"])
    & (raw["hour"] == picked["hour"])
    & (raw["channel"] == pick_channel)
].copy()
raw_for_snapshot["naive_flag"] = (raw_for_snapshot["rssi_dbm"] > ENERGY_DETECTION_THRESHOLD_DBM).astype(int)
st.caption(
    f"Every node's raw reading feeding the {pick_channel} verdict above -- disclosed, not "
    "hidden behind the fused score."
)
st.dataframe(
    raw_for_snapshot[["node_id", "rssi_dbm", "sensing_confidence", "naive_flag"]].sort_values("node_id"),
    use_container_width=True,
)

with st.expander("Audit log (every channel classified, fully explained)"):
    st.caption(
        "Internally the constraint engine still records its historical GRANTED/DENIED "
        "wording (unchanged, fully tested) -- read GRANTED as 'verified idle' and DENIED as "
        "'flagged for review' under the current framing."
    )
    st.dataframe(pd.DataFrame([d.to_dict() for d in decisions]), use_container_width=True)

with st.expander("Rules layer currently loaded (illustrative placeholder -- see data/DATASET_STATEMENT.md)"):
    st.json(rules)
